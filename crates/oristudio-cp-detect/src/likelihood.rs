/// 3×3 binomial blur, borders replicated.
fn gaussian3(luma: &[u8], w: usize, h: usize) -> Vec<u8> {
    let at = |x: isize, y: isize| -> u32 {
        let xc = x.clamp(0, w as isize - 1) as usize;
        let yc = y.clamp(0, h as isize - 1) as usize;
        luma[yc * w + xc] as u32
    };
    let mut out = vec![0u8; w * h];
    for y in 0..h as isize {
        for x in 0..w as isize {
            let sum = at(x - 1, y - 1)
                + 2 * at(x, y - 1)
                + at(x + 1, y - 1)
                + 2 * at(x - 1, y)
                + 4 * at(x, y)
                + 2 * at(x + 1, y)
                + at(x - 1, y + 1)
                + 2 * at(x, y + 1)
                + at(x + 1, y + 1);
            out[y as usize * w + x as usize] = ((sum + 8) / 16) as u8;
        }
    }
    out
}

/// 3×3 Sobel, borders replicated, unnormalised like OpenCV's.
fn sobel(img: &[u8], w: usize, h: usize) -> (Vec<i32>, Vec<i32>) {
    let at = |x: isize, y: isize| -> i32 {
        let xc = x.clamp(0, w as isize - 1) as usize;
        let yc = y.clamp(0, h as isize - 1) as usize;
        img[yc * w + xc] as i32
    };
    let mut gx = vec![0i32; w * h];
    let mut gy = vec![0i32; w * h];
    for y in 0..h as isize {
        for x in 0..w as isize {
            let o = y as usize * w + x as usize;
            gx[o] = -at(x - 1, y - 1) + at(x + 1, y - 1) - 2 * at(x - 1, y) + 2 * at(x + 1, y)
                - at(x - 1, y + 1)
                + at(x + 1, y + 1);
            gy[o] = -at(x - 1, y - 1) - 2 * at(x, y - 1) - at(x + 1, y - 1)
                + at(x - 1, y + 1)
                + 2 * at(x, y + 1)
                + at(x + 1, y + 1);
        }
    }
    (gx, gy)
}

/// Canny on precomputed gradients: L1 magnitude, OpenCV's four-direction
/// non-maximum suppression, hysteresis from the strong pixels outward.
fn canny(gx: &[i32], gy: &[i32], w: usize, h: usize, low: i32, high: i32) -> Vec<bool> {
    const SHIFT: i32 = 15;
    const TG22: i64 = 13_573; // tan(22.5°) << SHIFT
    let mag: Vec<i32> = gx
        .iter()
        .zip(gy)
        .map(|(&x, &y)| x.abs() + y.abs())
        .collect();
    let at = |x: isize, y: isize| -> i32 {
        if x < 0 || y < 0 || x >= w as isize || y >= h as isize {
            0
        } else {
            mag[y as usize * w + x as usize]
        }
    };
    // 0 = not an edge, 1 = passed suppression and the low threshold, 2 = edge
    let mut state = vec![0u8; w * h];
    let mut stack = Vec::new();
    for y in 0..h as isize {
        for x in 0..w as isize {
            let o = y as usize * w + x as usize;
            let m = mag[o];
            if m <= low {
                continue;
            }
            let xs = gx[o] as i64;
            let ys = gy[o] as i64;
            let ax = xs.abs();
            let ay = ys.abs() << SHIFT;
            let tg22x = ax * TG22;
            let keep = if ay < tg22x {
                m > at(x - 1, y) && m >= at(x + 1, y)
            } else {
                let tg67x = tg22x + (ax << (SHIFT + 1));
                if ay > tg67x {
                    m > at(x, y - 1) && m >= at(x, y + 1)
                } else {
                    let s: isize = if (xs ^ ys) < 0 { -1 } else { 1 };
                    m > at(x - s, y - 1) && m > at(x + s, y + 1)
                }
            };
            if !keep {
                continue;
            }
            if m > high {
                state[o] = 2;
                stack.push(o);
            } else {
                state[o] = 1;
            }
        }
    }
    while let Some(o) = stack.pop() {
        let x = (o % w) as isize;
        let y = (o / w) as isize;
        for dy in -1..=1 {
            for dx in -1..=1 {
                let nx = x + dx;
                let ny = y + dy;
                if nx < 0 || ny < 0 || nx >= w as isize || ny >= h as isize {
                    continue;
                }
                let no = ny as usize * w + nx as usize;
                if state[no] == 1 {
                    state[no] = 2;
                    stack.push(no);
                }
            }
        }
    }
    state.into_iter().map(|s| s == 2).collect()
}

