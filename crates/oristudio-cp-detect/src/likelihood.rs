/// Mark a segment 3 px wide: Bresenham along it, a 3×3 stamp at each step.
fn draw_thick_segment(map: &mut [bool], w: usize, h: usize, a: (i32, i32), b: (i32, i32)) {
    let (mut x, mut y) = a;
    let (x1, y1) = b;
    let dx = (x1 - x).abs();
    let dy = -(y1 - y).abs();
    let sx = if x < x1 { 1 } else { -1 };
    let sy = if y < y1 { 1 } else { -1 };
    let mut err = dx + dy;
    loop {
        for oy in -1..=1 {
            for ox in -1..=1 {
                let px = x + ox;
                let py = y + oy;
                if px >= 0 && py >= 0 && (px as usize) < w && (py as usize) < h {
                    map[py as usize * w + px as usize] = true;
                }
            }
        }
        if x == x1 && y == y1 {
            break;
        }
        let e2 = 2 * err;
        if e2 >= dy {
            err += dy;
            x += sx;
        }
        if e2 <= dx {
            err += dx;
            y += sy;
        }
    }
}

/// Peak of the normalised autocorrelation at lags between 4 and a third of the
/// profile: periodic ink (graph paper, bricks, blinds) scores near 1.
fn profile_periodicity(profile: &[f64]) -> f32 {
    let n = profile.len();
    if n < 32 {
        return 0.0;
    }
    let mean = profile.iter().sum::<f64>() / n as f64;
    let centred: Vec<f64> = profile.iter().map(|v| v - mean).collect();
    if centred.iter().map(|v| v.abs()).sum::<f64>() < 1e-6 {
        return 0.0;
    }
    let ac0: f64 = centred.iter().map(|v| v * v).sum::<f64>().max(1e-9);
    let hi = (n / 3).max(5);
    let mut best = f64::MIN;
    for lag in 4..hi {
        let ac: f64 = centred[..n - lag]
            .iter()
            .zip(&centred[lag..])
            .map(|(a, b)| a * b)
            .sum();
        best = best.max(ac / ac0);
    }
    best as f32
}

