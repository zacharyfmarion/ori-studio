fn percentile_sorted(values: &[u32], p: f64) -> f64 {
    if values.is_empty() {
        return 0.0;
    }
    let pos = p * (values.len() - 1) as f64;
    let lo = pos.floor() as usize;
    let hi = pos.ceil() as usize;
    let frac = pos - lo as f64;
    values[lo] as f64 * (1.0 - frac) + values[hi] as f64 * frac
}

/// `(ink_bbox_fill, ink_bbox_aspect, cells_covered, cells_cv)`.
fn coverage(ink: &[bool], w: usize, h: usize) -> (f32, f32, f32, f32) {
    let mut xs = Vec::new();
    let mut ys = Vec::new();
    for y in 0..h {
        for x in 0..w {
            if ink[y * w + x] {
                xs.push(x as u32);
                ys.push(y as u32);
            }
        }
    }
    if xs.len() <= 20 {
        return (0.0, 1.0, 0.0, 9.0);
    }
    let mut sx = xs.clone();
    let mut sy = ys.clone();
    sx.sort_unstable();
    sy.sort_unstable();
    let x0 = percentile_sorted(&sx, 0.01);
    let x1 = percentile_sorted(&sx, 0.99);
    let y0 = percentile_sorted(&sy, 0.01);
    let y1 = percentile_sorted(&sy, 0.99);
    let bw = (x1 - x0).max(1.0);
    let bh = (y1 - y0).max(1.0);
    const G: usize = 6;
    let mut cells = [0f64; G * G];
    for (&x, &y) in xs.iter().zip(&ys) {
        let cx = (((x as f64 - x0) / bw * G as f64) as i64).clamp(0, G as i64 - 1) as usize;
        let cy = (((y as f64 - y0) / bh * G as f64) as i64).clamp(0, G as i64 - 1) as usize;
        cells[cy * G + cx] += 1.0;
    }
    let cell_area = bw * bh / (G * G) as f64;
    for cell in cells.iter_mut() {
        *cell /= cell_area;
    }
    let covered = cells.iter().filter(|&&c| c > 0.01).count() as f64 / (G * G) as f64;
    let mean = cells.iter().sum::<f64>() / (G * G) as f64;
    let var = cells.iter().map(|c| (c - mean).powi(2)).sum::<f64>() / (G * G) as f64;
    let cv = var.sqrt() / (mean + 1e-9);
    (
        (bw * bh / (w * h) as f64) as f32,
        (bw.max(bh) / bw.min(bh)) as f32,
        covered as f32,
        cv as f32,
    )
}

/// OpenCV-style HSV: hue 0–179, saturation and value 0–255.
fn hsv(r: u8, g: u8, b: u8) -> (u8, u8, u8) {
    let (r, g, b) = (r as f32, g as f32, b as f32);
    let max = r.max(g).max(b);
    let min = r.min(g).min(b);
    let v = max;
    let s = if max > 0.0 {
        255.0 * (max - min) / max
    } else {
        0.0
    };
    let h = if max == min {
        0.0
    } else if max == r {
        60.0 * (g - b) / (max - min)
    } else if max == g {
        120.0 + 60.0 * (b - r) / (max - min)
    } else {
        240.0 + 60.0 * (r - g) / (max - min)
    };
    let h = if h < 0.0 { h + 360.0 } else { h };
    (
        (h / 2.0).round() as u8 % 180,
        s.round() as u8,
        v.round() as u8,
    )
}

/// `(ink_chroma_frac, hue_top2, img_sat_mean)`.
fn colour_features(raster: &Raster, ink: &[bool]) -> (f32, f32, f32) {
    let n = raster.width * raster.height;
    let mut sat_sum = 0u64;
    let mut ink_n = 0usize;
    let mut chroma_n = 0usize;
    let mut hues = [0u32; 18];
    for (((&r, &g), &b), &is_ink) in raster.r.iter().zip(&raster.g).zip(&raster.b).zip(ink) {
        let (hue, s, v) = hsv(r, g, b);
        sat_sum += s as u64;
        if is_ink {
            ink_n += 1;
            if s > 90 && v > 50 {
                chroma_n += 1;
                hues[(hue / 10).min(17) as usize] += 1;
            }
        }
    }
    let img_sat_mean = sat_sum as f32 / n as f32 / 255.0;
    if ink_n <= 20 {
        return (0.0, 1.0, img_sat_mean);
    }
    let chroma_frac = chroma_n as f32 / ink_n as f32;
    let hue_top2 = if chroma_n > 20 {
        let mut sorted = hues;
        sorted.sort_unstable();
        (sorted[16] + sorted[17]) as f32 / chroma_n as f32
    } else {
        1.0
    };
    (chroma_frac, hue_top2, img_sat_mean)
}

