/// Zhang–Suen thinning; deletions within a sub-iteration are simultaneous.
fn zhang_suen(mask: &[bool], w: usize, h: usize) -> Vec<bool> {
    let pw = w + 2;
    let mut img = vec![0u8; pw * (h + 2)];
    for y in 0..h {
        for x in 0..w {
            img[(y + 1) * pw + x + 1] = mask[y * w + x] as u8;
        }
    }
    let mut remove = Vec::new();
    for _ in 0..60 {
        let mut changed = false;
        for step in 0..2 {
            remove.clear();
            for y in 1..=h {
                for x in 1..=w {
                    let o = y * pw + x;
                    if img[o] == 0 {
                        continue;
                    }
                    let p2 = img[o - pw];
                    let p3 = img[o - pw + 1];
                    let p4 = img[o + 1];
                    let p5 = img[o + pw + 1];
                    let p6 = img[o + pw];
                    let p7 = img[o + pw - 1];
                    let p8 = img[o - 1];
                    let p9 = img[o - pw - 1];
                    let b = p2 + p3 + p4 + p5 + p6 + p7 + p8 + p9;
                    if !(2..=6).contains(&b) {
                        continue;
                    }
                    let seq = [p2, p3, p4, p5, p6, p7, p8, p9, p2];
                    let a = seq
                        .windows(2)
                        .filter(|pair| pair[0] == 0 && pair[1] == 1)
                        .count();
                    if a != 1 {
                        continue;
                    }
                    let (c1, c2) = if step == 0 {
                        (p2 * p4 * p6 == 0, p4 * p6 * p8 == 0)
                    } else {
                        (p2 * p4 * p8 == 0, p2 * p6 * p8 == 0)
                    };
                    if c1 && c2 {
                        remove.push(o);
                    }
                }
            }
            if !remove.is_empty() {
                changed = true;
                for &o in &remove {
                    img[o] = 0;
                }
            }
        }
        if !changed {
            break;
        }
    }
    let mut out = vec![false; w * h];
    for y in 0..h {
        for x in 0..w {
            out[y * w + x] = img[(y + 1) * pw + x + 1] == 1;
        }
    }
    out
}

struct SkeletonStats {
    pixels: usize,
    /// Crossing number 1.
    endpoints: usize,
    /// 8-connected clusters of pixels with crossing number ≥ 3 — a thick
    /// crossing is one junction, not four.
    junctions: usize,
}

fn skeleton_stats(skeleton: &[bool], w: usize, h: usize) -> SkeletonStats {
    let at = |x: isize, y: isize| -> u8 {
        if x < 0 || y < 0 || x >= w as isize || y >= h as isize {
            0
        } else {
            skeleton[y as usize * w + x as usize] as u8
        }
    };
    let mut pixels = 0;
    let mut endpoints = 0;
    let mut junction_px = vec![false; w * h];
    for y in 0..h as isize {
        for x in 0..w as isize {
            if !skeleton[y as usize * w + x as usize] {
                continue;
            }
            pixels += 1;
            let ring = [
                at(x, y - 1),
                at(x + 1, y - 1),
                at(x + 1, y),
                at(x + 1, y + 1),
                at(x, y + 1),
                at(x - 1, y + 1),
                at(x - 1, y),
                at(x - 1, y - 1),
            ];
            let crossings = (0..8)
                .filter(|&i| ring[i] == 0 && ring[(i + 1) % 8] == 1)
                .count();
            if crossings == 1 {
                endpoints += 1;
            } else if crossings >= 3 {
                junction_px[y as usize * w + x as usize] = true;
            }
        }
    }
    // 8-connected components of the junction pixels
    let mut seen = vec![false; w * h];
    let mut junctions = 0;
    let mut stack = Vec::new();
    for start in 0..w * h {
        if !junction_px[start] || seen[start] {
            continue;
        }
        junctions += 1;
        seen[start] = true;
        stack.push(start);
        while let Some(o) = stack.pop() {
            let x = (o % w) as isize;
            let y = (o / w) as isize;
            for dy in -1..=1 {
                for dx in -1..=1 {
                    let nx = x + dx;
                    let ny = y + dy;
                    if nx < 0 || ny < 0 || nx >= w as isize || ny >= h as isize {
                        continue;
                    }
                    let no = ny as usize * w + nx as usize;
                    if junction_px[no] && !seen[no] {
                        seen[no] = true;
                        stack.push(no);
                    }
                }
            }
        }
    }
    SkeletonStats {
        pixels,
        endpoints,
        junctions,
    }
}

