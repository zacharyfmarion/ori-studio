// Orientation histogram

struct Orientation {
    top4_mass: f32,
    n_peaks: u32,
    lattice22: f32,
    lattice45: f32,
    lattice90: f32,
    diag_mass: f32,
    axis_mass: f32,
    entropy: f32,
}

/// Mass within `halfwidth` degrees of each centre, each bin counted once.
fn peak_mass(hist: &[f64; 180], centres: &[f64], halfwidth: f64) -> f64 {
    let mut used = [false; 180];
    let mut mass = 0.0;
    for &c in centres {
        let lo = (c - halfwidth).floor() as i64;
        let hi = (c + halfwidth).ceil() as i64;
        for i in lo..=hi {
            let idx = i.rem_euclid(180) as usize;
            if !used[idx] {
                used[idx] = true;
                mass += hist[idx];
            }
        }
    }
    mass
}

fn orientation_features(gx: &[i32], gy: &[i32], edges: &[bool]) -> Orientation {
    let mut hist = [0f64; 180];
    let mut count = 0usize;
    for (o, &edge) in edges.iter().enumerate() {
        if !edge {
            continue;
        }
        count += 1;
        let x = gx[o] as f64;
        let y = gy[o] as f64;
        let angle = (y.atan2(x).to_degrees() + 180.0).rem_euclid(180.0);
        let bin = (angle.floor() as i64).rem_euclid(180) as usize;
        hist[bin] += (x * x + y * y).sqrt();
    }
    if count < 50 {
        return Orientation {
            top4_mass: 0.0,
            n_peaks: 0,
            lattice22: 0.0,
            lattice45: 0.0,
            lattice90: 0.0,
            diag_mass: 0.0,
            axis_mass: 0.0,
            entropy: 1.0,
        };
    }
    let mut smooth = [0f64; 180];
    for i in 0..180 {
        smooth[i] = (hist[(i + 179) % 180] + 2.0 * hist[i] + hist[(i + 1) % 180]) / 4.0;
    }
    let hist = smooth;
    let total = hist.iter().sum::<f64>() + 1e-9;
    let entropy = -hist
        .iter()
        .filter(|&&v| v > 0.0)
        .map(|&v| {
            let p = v / total;
            p * p.ln()
        })
        .sum::<f64>()
        / 180f64.ln();

    let mut peaks: Vec<usize> = (0..180)
        .filter(|&i| hist[i] >= hist[(i + 179) % 180] && hist[i] > hist[(i + 1) % 180])
        .collect();
    peaks.sort_by(|&a, &b| hist[b].total_cmp(&hist[a]));
    let mut chosen: Vec<usize> = Vec::new();
    for i in peaks {
        let apart = chosen.iter().all(|&j| {
            let d = (i as i64 - j as i64).abs();
            d.min(180 - d) >= 6
        });
        if apart {
            chosen.push(i);
        }
        if chosen.len() >= 8 {
            break;
        }
    }
    let top: Vec<f64> = chosen.iter().take(4).map(|&i| i as f64).collect();
    let top4_mass = peak_mass(&hist, &top, 3.0) / total;
    let n_peaks = chosen
        .iter()
        .filter(|&&i| peak_mass(&hist, &[i as f64], 3.0) / total >= 0.04)
        .count() as u32;

    let sweep = |period: f64, count: usize| -> (f64, f64) {
        let mut best = 0.0;
        let mut best_phi = 0.0;
        let steps = (period / 0.5) as usize;
        for step in 0..steps {
            let phi = step as f64 * 0.5;
            let centres: Vec<f64> = (0..count).map(|k| phi + k as f64 * period).collect();
            let mass = peak_mass(&hist, &centres, 2.5) / total;
            if mass > best {
                best = mass;
                best_phi = phi;
            }
        }
        (best, best_phi)
    };
    let (lattice22, best_phi) = sweep(22.5, 8);
    let (lattice45, _) = sweep(45.0, 4);
    let (lattice90, _) = sweep(90.0, 2);

    let axis_masses: Vec<f64> = (0..8)
        .map(|k| {
            peak_mass(
                &hist,
                &[(best_phi + k as f64 * 22.5).rem_euclid(180.0)],
                2.5,
            ) / total
        })
        .collect();
    let k0 = axis_masses
        .iter()
        .enumerate()
        .fold(
            (0usize, f64::MIN),
            |best, (i, &v)| if v > best.1 { (i, v) } else { best },
        )
        .0;
    let axis_mass = axis_masses[k0] + axis_masses[(k0 + 4) % 8];
    let diag_mass = axis_masses[(k0 + 2) % 8] + axis_masses[(k0 + 6) % 8];

    Orientation {
        top4_mass: top4_mass as f32,
        n_peaks,
        lattice22: lattice22 as f32,
        lattice45: lattice45 as f32,
        lattice90: lattice90 as f32,
        diag_mass: diag_mass as f32,
        axis_mass: axis_mass as f32,
        entropy: entropy as f32,
    }
}

