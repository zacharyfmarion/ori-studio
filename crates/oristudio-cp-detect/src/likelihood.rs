    #[test]
    fn blank_and_noise_and_text_are_not_offered() {
        let (w, h) = (400usize, 400usize);
        let blank = vec![255u8; w * h];
        let v = verdict_of(&blank, w, h);
        assert!(!v.likely, "blank scored {}", v.score);

        // value noise with smooth blobs: a photograph's texture, no straight lines
        let mut seed = 12345u32;
        let mut coarse = vec![0f32; 20 * 20];
        for cell in coarse.iter_mut() {
            seed = seed.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
            *cell = (seed >> 8) as f32 / (1u32 << 24) as f32;
        }
        let mut noise = vec![0u8; w * h];
        for y in 0..h {
            for x in 0..w {
                let fx = x as f32 / w as f32 * 19.0;
                let fy = y as f32 / h as f32 * 19.0;
                let (x0, y0) = (fx.floor() as usize, fy.floor() as usize);
                let (tx, ty) = (fx - x0 as f32, fy - y0 as f32);
                let c = |i: usize, j: usize| coarse[j.min(19) * 20 + i.min(19)];
                let v = c(x0, y0) * (1.0 - tx) * (1.0 - ty)
                    + c(x0 + 1, y0) * tx * (1.0 - ty)
                    + c(x0, y0 + 1) * (1.0 - tx) * ty
                    + c(x0 + 1, y0 + 1) * tx * ty;
                seed = seed.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
                let grain = ((seed >> 24) as f32 - 128.0) * 0.15;
                noise[y * w + x] = (v * 200.0 + 30.0 + grain).clamp(0.0, 255.0) as u8;
            }
        }
        let v = verdict_of(&noise, w, h);
        assert!(!v.likely, "noise scored {}", v.score);

        let mut text = vec![255u8; w * h];
        let mut seed = 7u32;
        for row in 0..14 {
            let y = 30.0 + row as f64 * 26.0;
            let mut x = 30.0;
            while x < 360.0 {
                seed = seed.wrapping_mul(1_103_515_245).wrapping_add(12_345);
                let len = 6.0 + (seed >> 16) as f64 % 18.0;
                line(&mut text, w, h, (x, y), (x + len, y), 0);
                line(&mut text, w, h, (x, y - 6.0), (x, y), 0);
                x += len + 8.0;
            }
        }
        let v = verdict_of(&text, w, h);
        assert!(!v.likely, "text scored {}", v.score);
    }

