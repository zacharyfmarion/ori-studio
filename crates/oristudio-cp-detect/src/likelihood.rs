//! Is this image a crease pattern?
//!
//! The gate behind the "Looks like a crease pattern — Detect creases?" offer
//! on a reference image added to the Edit canvas. It has to answer for every
//! image a user drops there, so it runs in a few tens of milliseconds, needs no
//! model download and no ONNX Runtime, and is tuned to stay quiet on what
//! people actually put on that canvas: photographs of folded models, diagram
//! pages, text.
//!
//! The answer comes from about twenty hand features computed on a ≤512 px
//! copy, combined by a small table of shallow decision trees
//! (`likelihood_model.rs`, generated by
//! `scripts/cp-detect/cp-likelihood/fit-model.py` from features this very
//! module produced — there is deliberately no second implementation of the
//! features to drift from). The features that carry the weight are the ones a
//! crease pattern cannot fake:
//!
//! - **Straight-line length** — a probabilistic Hough pass (the crate's
//!   OpenCV port) over Canny edges, and the share of edge pixels those
//!   segments explain.
//! - **Dangling ends** — on a Zhang–Suen skeleton of the ink, the share of
//!   pixels that are endpoints. Creases end at other creases, so a crease
//!   pattern reads ~0; text, diagrams and photographs read 5–20%.
//! - **Orientation lattice** — gradient orientations at edge pixels
//!   concentrate on a 22.5° lattice, with mass on the diagonals; a photograph
//!   is diffuse, a table or floor plan has axes only.
//! - **Full-span segments** — the share of Hough length in segments crossing
//!   most of the image, which is what separates graph paper, blinds and
//!   random full-width lines from a pattern whose creases stop at each other.
//! - Background fraction, coverage uniformity, ink saturation and a
//!   periodicity of the ink projection round it out.
//!
//! Measured on the labelled corpus (see the plan
//! `implementation-plans/cp-detect-canvas-image-entry.md` for the numbers):
//! AUC ≈ 0.98, ~92% recall at ~2% false positives on folded-model photos,
//! ~0% on photographs, text, tables, plans and charts. Evenly spaced grids
//! are the accepted residual — a grid *is* a precrease pattern.

use serde::{Deserialize, Serialize};

use crate::likelihood_model;
use crate::opencv_hough_lines_p::{HoughLinesPConfig, hough_lines_p_opencv_cpu};

/// Longest side the features are computed at. Larger inputs are area-averaged
/// down first; a caller that already has a copy no larger than this saves the
/// resample (and the transfer, on the worker).
pub const LIKELIHOOD_MAX_SIDE: u32 = 512;

/// Number of features the model reads, in [`MODEL_FEATURES`] order.
pub const MODEL_FEATURE_COUNT: usize = 20;

/// The model's input vector, by name and in order. `likelihood_model.rs` must
/// carry the same list — a test checks — so a refit that reorders features
/// cannot silently read the wrong column.
pub const MODEL_FEATURES: [&str; MODEL_FEATURE_COUNT] = [
    "bg_frac",
    "gray_std",
    "lattice22",
    "top4_mass",
    "orient_entropy",
    "line_len_norm",
    "long_line_ratio",
    "endpoint_rate",
    "junction_rate",
    "ends_per_junction",
    "cells_cv",
    "cells_covered",
    "ink_frac",
    "img_sat_mean",
    "diag_mass",
    "ink_to_skel",
    "full_span_frac",
    "mean_seg_len_norm",
    "periodicity",
    "n_peaks",
];

#[derive(Debug, thiserror::Error)]
pub enum LikelihoodError {
    #[error("invalid image dimensions: {width}x{height}")]
    InvalidDimensions { width: u32, height: u32 },
    #[error("rgba length mismatch: expected {expected}, got {actual}")]
    RgbaLengthMismatch { expected: usize, actual: usize },
}

/// Everything the extractor measures. The model reads the [`MODEL_FEATURES`]
/// subset; the rest is kept for the harness and for diagnosing a verdict in
/// the field (`cp_likelihood_score` prints all of it).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CpLikelihoodFeatures {
    /// Size the features were computed at.
    pub width: u32,
    pub height: u32,
    pub aspect: f32,
    /// Share of pixels within ±12 of the luma histogram's mode.
    pub bg_frac: f32,
    pub gray_std: f32,
    /// Share of pixels that differ from a 21 px median by more than 24.
    pub ink_frac: f32,
    /// Share of pixels Canny marks as edges.
    pub edge_frac: f32,
    /// Orientation histogram: mass under the four strongest peaks (±3°).
    pub top4_mass: f32,
    /// Peaks holding at least 4% of the orientation mass each.
    pub n_peaks: u32,
    /// Best mass within ±2.5° of a 22.5° lattice, over all lattice offsets.
    pub lattice22: f32,
    pub lattice45: f32,
    pub lattice90: f32,
    /// In the best 22.5° frame: mass on the two axes 45° from the strongest pair.
    pub diag_mass: f32,
    /// Mass on the strongest axis pair itself.
    pub axis_mass: f32,
    /// Normalised entropy of the orientation histogram (1 = uniform).
    pub orient_entropy: f32,
    /// Probabilistic Hough segments found.
    pub n_lines: u32,
    /// Total segment length over the image's shorter side.
    pub line_len_norm: f32,
    /// Share of edge pixels lying on a segment (drawn 3 px wide).
    pub long_line_ratio: f32,
    /// Share of segment length in segments at least 75% of the shorter side.
    pub full_span_frac: f32,
    pub mean_seg_len_norm: f32,
    /// Peak normalised autocorrelation of the ink's row and column sums.
    pub periodicity: f32,
    /// Skeleton pixels over image pixels.
    pub skel_px_frac: f32,
    /// Skeleton endpoints over skeleton pixels.
    pub endpoint_rate: f32,
    /// Skeleton junction clusters over skeleton pixels.
    pub junction_rate: f32,
    pub ends_per_junction: f32,
    pub n_endpoints: u32,
    pub n_junctions: u32,
    /// Ink pixels per skeleton pixel: a mean stroke width.
    pub ink_to_skel: f32,
    /// The ink's 1st–99th percentile box as a share of the image.
    pub ink_bbox_fill: f32,
    pub ink_bbox_aspect: f32,
    /// Share of 6×6 cells over that box holding ink; and their spread.
    pub cells_covered: f32,
    pub cells_cv: f32,
    /// Share of ink pixels that are saturated; and how few hues they use.
    pub ink_chroma_frac: f32,
    pub hue_top2: f32,
    /// Mean HSV saturation of the whole image.
    pub img_sat_mean: f32,
}

impl CpLikelihoodFeatures {
    /// The model's input, in [`MODEL_FEATURES`] order.
    pub fn model_vector(&self) -> [f32; MODEL_FEATURE_COUNT] {
        [
            self.bg_frac,
            self.gray_std,
            self.lattice22,
            self.top4_mass,
            self.orient_entropy,
            self.line_len_norm,
            self.long_line_ratio,
            self.endpoint_rate,
            self.junction_rate,
            self.ends_per_junction,
            self.cells_cv,
            self.cells_covered,
            self.ink_frac,
            self.img_sat_mean,
            self.diag_mass,
            self.ink_to_skel,
            self.full_span_frac,
            self.mean_seg_len_norm,
            self.periodicity,
            self.n_peaks as f32,
        ]
    }
}

/// The verdict on one image.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CpLikelihood {
    /// Model probability, 0–1.
    pub score: f32,
    /// `score >= threshold`: the offer is made.
    pub likely: bool,
    /// The operating point the model was tuned to (see `likelihood_model.rs`).
    pub threshold: f32,
    pub features: CpLikelihoodFeatures,
}

/// Score an RGBA image. Any size; it is resampled to [`LIKELIHOOD_MAX_SIDE`].
pub fn crease_pattern_likelihood(
    rgba: &[u8],
    width: u32,
    height: u32,
) -> Result<CpLikelihood, LikelihoodError> {
    debug_assert_eq!(likelihood_model::FEATURE_NAMES, MODEL_FEATURES);
    let features = extract_features(rgba, width, height)?;
    let score = score_features(&features);
    Ok(CpLikelihood {
        score,
        likely: score >= likelihood_model::THRESHOLD,
        threshold: likelihood_model::THRESHOLD,
        features,
    })
}

/// The model's probability for a feature set.
pub fn score_features(features: &CpLikelihoodFeatures) -> f32 {
    let raw = likelihood_model::raw_score(&features.model_vector());
    1.0 / (1.0 + (-raw).exp())
}

/// The features alone — what the harness fits the model on.
pub fn extract_features(
    rgba: &[u8],
    width: u32,
    height: u32,
) -> Result<CpLikelihoodFeatures, LikelihoodError> {
    if width == 0 || height == 0 {
        return Err(LikelihoodError::InvalidDimensions { width, height });
    }
    let expected = width as usize * height as usize * 4;
    if rgba.len() != expected {
        return Err(LikelihoodError::RgbaLengthMismatch {
            expected,
            actual: rgba.len(),
        });
    }
    let raster = downscale_rgba(rgba, width as usize, height as usize);
    Ok(features_of(&raster))
}

// ---------------------------------------------------------------------------
// Raster

struct Raster {
    width: usize,
    height: usize,
    r: Vec<u8>,
    g: Vec<u8>,
    b: Vec<u8>,
    luma: Vec<u8>,
}

/// Area-average resample to at most [`LIKELIHOOD_MAX_SIDE`] on the longer
/// side, compositing alpha over white (a transparent PNG background reads as
/// paper, not as black).
fn downscale_rgba(rgba: &[u8], width: usize, height: usize) -> Raster {
    let scale = (LIKELIHOOD_MAX_SIDE as f64 / width.max(height) as f64).min(1.0);
    let dw = ((width as f64 * scale).round() as usize).clamp(1, width);
    let dh = ((height as f64 * scale).round() as usize).clamp(1, height);
    let mut raster = Raster {
        width: dw,
        height: dh,
        r: vec![0; dw * dh],
        g: vec![0; dw * dh],
        b: vec![0; dw * dh],
        luma: vec![0; dw * dh],
    };
    for dy in 0..dh {
        let y0 = dy * height / dh;
        let y1 = ((dy + 1) * height / dh).max(y0 + 1).min(height);
        for dx in 0..dw {
            let x0 = dx * width / dw;
            let x1 = ((dx + 1) * width / dw).max(x0 + 1).min(width);
            let (mut sr, mut sg, mut sb, mut n) = (0u64, 0u64, 0u64, 0u64);
            for y in y0..y1 {
                let row = y * width;
                for x in x0..x1 {
                    let i = (row + x) * 4;
                    let a = rgba[i + 3] as u64;
                    let inv = 255 - a;
                    sr += (rgba[i] as u64 * a + 255 * inv) / 255;
                    sg += (rgba[i + 1] as u64 * a + 255 * inv) / 255;
                    sb += (rgba[i + 2] as u64 * a + 255 * inv) / 255;
                    n += 1;
                }
            }
            let r = (sr / n) as u8;
            let g = (sg / n) as u8;
            let b = (sb / n) as u8;
            let o = dy * dw + dx;
            raster.r[o] = r;
            raster.g[o] = g;
            raster.b[o] = b;
            raster.luma[o] = (0.299 * r as f32 + 0.587 * g as f32 + 0.114 * b as f32).round() as u8;
        }
    }
    raster
}

// ---------------------------------------------------------------------------
// Features

fn features_of(raster: &Raster) -> CpLikelihoodFeatures {
    let (w, h) = (raster.width, raster.height);
    let n_px = (w * h) as f32;
    let luma = &raster.luma;

    // --- background level and spread
    let mut hist = [0f64; 256];
    for &v in luma {
        hist[v as usize] += 1.0;
    }
    let mut smooth = [0f64; 256];
    for (i, slot) in smooth.iter_mut().enumerate() {
        let lo = i.saturating_sub(4);
        let hi = (i + 4).min(255);
        *slot = hist[lo..=hi].iter().sum::<f64>() / 9.0;
    }
    let bg = smooth
        .iter()
        .enumerate()
        .fold(
            (0usize, f64::MIN),
            |best, (i, &v)| if v > best.1 { (i, v) } else { best },
        )
        .0 as i32;
    let bg_frac = luma
        .iter()
        .filter(|&&v| (v as i32 - bg).abs() <= 12)
        .count() as f32
        / n_px;
    let mean = luma.iter().map(|&v| v as f64).sum::<f64>() / n_px as f64;
    let var = luma.iter().map(|&v| (v as f64 - mean).powi(2)).sum::<f64>() / n_px as f64;
    let gray_std = var.sqrt() as f32;

    // --- ink: local contrast against a 21 px median
    let median = {
        let img = image::GrayImage::from_raw(w as u32, h as u32, luma.clone())
            .expect("raster dimensions match its buffer");
        imageproc::filter::median_filter(&img, 10, 10).into_raw()
    };
    let ink: Vec<bool> = luma
        .iter()
        .zip(&median)
        .map(|(&v, &m)| (v as i32 - m as i32).abs() > 24)
        .collect();
    let ink_count = ink.iter().filter(|&&v| v).count();
    let ink_frac = ink_count as f32 / n_px;

    // --- edges and orientation
    let blur = gaussian3(luma, w, h);
    let (gx, gy) = sobel(&blur, w, h);
    let edges = canny(&gx, &gy, w, h, 60, 160);
    let edge_count = edges.iter().filter(|&&v| v).count();
    let edge_frac = edge_count as f32 / n_px;
    let orient = orientation_features(&gx, &gy, &edges);

    // --- straight segments
    let m = w.min(h) as f64;
    let hough = HoughLinesPConfig {
        rho: 1.0,
        theta: std::f32::consts::PI / 180.0,
        threshold: ((m * 0.03) as i32).max(20),
        min_line_length: ((m * 0.04) as i32).max(20) as f64,
        max_line_gap: 4.0,
        lines_max: i32::MAX,
    };
    let edge_u8: Vec<u8> = edges.iter().map(|&e| if e { 255 } else { 0 }).collect();
    let segments = hough_lines_p_opencv_cpu(&edge_u8, w, h, &hough).unwrap_or_default();
    let mut line_map = vec![false; w * h];
    let mut total_len = 0.0f64;
    let mut full_span_len = 0.0f64;
    for segment in &segments {
        draw_thick_segment(
            &mut line_map,
            w,
            h,
            (segment.x1, segment.y1),
            (segment.x2, segment.y2),
        );
        let len = (((segment.x2 - segment.x1) as f64).powi(2)
            + ((segment.y2 - segment.y1) as f64).powi(2))
        .sqrt();
        total_len += len;
        if len >= 0.75 * m {
            full_span_len += len;
        }
    }
    let covered_edges = line_map
        .iter()
        .zip(&edges)
        .filter(|&(&l, &e)| l && e)
        .count();
    let n_lines = segments.len() as u32;
    let line_len_norm = (total_len / m) as f32;
    let long_line_ratio = covered_edges as f32 / edge_count.max(1) as f32;
    let full_span_frac = if total_len > 0.0 {
        (full_span_len / total_len) as f32
    } else {
        0.0
    };
    let mean_seg_len_norm = if segments.is_empty() {
        0.0
    } else {
        (total_len / segments.len() as f64 / m) as f32
    };

    // --- periodicity of the ink projections
    let periodicity = {
        let mut cols = vec![0f64; w];
        let mut rows = vec![0f64; h];
        for y in 0..h {
            for x in 0..w {
                if ink[y * w + x] {
                    cols[x] += 1.0;
                    rows[y] += 1.0;
                }
            }
        }
        profile_periodicity(&cols).max(profile_periodicity(&rows))
    };

    // --- skeleton statistics
    let (
        skel_px_frac,
        endpoint_rate,
        junction_rate,
        ends_per_junction,
        n_endpoints,
        n_junctions,
        ink_to_skel,
    ) = if ink_frac > 0.0005 && ink_frac < 0.6 {
        let skeleton = zhang_suen(&ink, w, h);
        let stats = skeleton_stats(&skeleton, w, h);
        let sp = stats.pixels as f32;
        (
            sp / n_px,
            stats.endpoints as f32 / sp.max(1.0),
            stats.junctions as f32 / sp.max(1.0),
            stats.endpoints as f32 / (stats.junctions as f32).max(1.0),
            stats.endpoints as u32,
            stats.junctions as u32,
            ink_count as f32 / sp.max(1.0),
        )
    } else {
        (0.0, 1.0, 0.0, 99.0, 0, 0, 99.0)
    };

    // --- coverage uniformity over the ink's own box
    let (ink_bbox_fill, ink_bbox_aspect, cells_covered, cells_cv) = coverage(&ink, w, h);

    // --- colour
    let (ink_chroma_frac, hue_top2, img_sat_mean) = colour_features(raster, &ink);

    CpLikelihoodFeatures {
        width: w as u32,
        height: h as u32,
        aspect: w.max(h) as f32 / w.min(h).max(1) as f32,
        bg_frac,
        gray_std,
        ink_frac,
        edge_frac,
        top4_mass: orient.top4_mass,
        n_peaks: orient.n_peaks,
        lattice22: orient.lattice22,
        lattice45: orient.lattice45,
        lattice90: orient.lattice90,
        diag_mass: orient.diag_mass,
        axis_mass: orient.axis_mass,
        orient_entropy: orient.entropy,
        n_lines,
        line_len_norm,
        long_line_ratio,
        full_span_frac,
        mean_seg_len_norm,
        periodicity,
        skel_px_frac,
        endpoint_rate,
        junction_rate,
        ends_per_junction,
        n_endpoints,
        n_junctions,
        ink_to_skel,
        ink_bbox_fill,
        ink_bbox_aspect,
        cells_covered,
        cells_cv,
        ink_chroma_frac,
        hue_top2,
        img_sat_mean,
    }
}

