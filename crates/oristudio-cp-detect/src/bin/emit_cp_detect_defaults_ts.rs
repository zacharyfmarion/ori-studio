//! Codegen: emit the canonical CP-detect decode defaults as a TypeScript module.
//!
//! Single source of truth is `oristudio_cp_detect::defaults`. The browser must
//! not hand-maintain a second copy of these constants (that drift is what made
//! the benchmark measure a different pipeline than the product). This bin prints
//! a `.ts` module to stdout; the web build writes it to a gitignored generated
//! file on every `build:wasm`, so it can never go stale.
//!
//!   cargo run -p oristudio-cp-detect --bin emit_cp_detect_defaults_ts \
//!     > apps/web/src/generated/cpDetectDefaults.generated.ts

use oristudio_cp_detect::defaults::{DEFAULT_JUNCTION_SOURCE, DEFAULT_LINE_EVIDENCE_SOURCE};

fn main() {
    print!(
        "// @generated by `cargo run -p oristudio-cp-detect --bin emit_cp_detect_defaults_ts`\n\
         // Source of truth: crates/oristudio-cp-detect/src/defaults.rs. DO NOT EDIT.\n\
         export const CP_DETECT_DEFAULT_JUNCTION_SOURCE = {junction:?} as const;\n\
         export const CP_DETECT_DEFAULT_LINE_EVIDENCE_SOURCE = {line:?} as const;\n",
        junction = DEFAULT_JUNCTION_SOURCE,
        line = DEFAULT_LINE_EVIDENCE_SOURCE,
    );
}
