#!/usr/bin/env node
/**
 * Builds the ReferenceFinder WebAssembly module from the vendored C++ core.
 *
 * Source:  third_party/reference-finder/src/core/**\/*.cpp  (Lang / Tsai / Shavit, GPL)
 * Output:  apps/web/src/generated/reference-finder/{ref.js,ref.wasm,ref.d.ts}
 *          (gitignored like every other kernel under src/generated/, and CI asserts it
 *          stays untracked). `--node` also links a `-sENVIRONMENT=worker,node` variant to
 *          artifacts/reference-finder-node/ for Node-side tests.
 *
 * Invoked from apps/web as `npm run build:reference-finder-wasm`, which `build:wasm` chains
 * so the `pre*` hooks rebuild it like the wasm-pack bridges. Decision D2 in
 * implementation-plans/reference-finder-integration.md is the design record.
 *
 * Toolchain: em++ from Emscripten 6.0.9, pinned in scripts/reference-finder-emsdk.json and
 * shared with .github/actions/install-emsdk. A different installed version only warns — the
 * output is checked for equivalence against upstream's artifact by
 * tools/reference-finder-oracle/equiv.mjs, not by byte identity.
 *
 * Fallback: when em++ is not on PATH and no output exists yet, the committed upstream
 * artifact at the pinned commit is downloaded and SHA-256 verified so `npm run dev` works
 * without Emscripten. It is a development convenience only: `REFERENCE_FINDER_FORCE_SOURCE=1`
 * (set in every CI build) makes a missing compiler fatal so a fetched binary can never
 * become a shipped one.
 */
import { spawn, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { cpus } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), '..');
const pinPath = join(repoRoot, 'scripts/reference-finder-emsdk.json');
const vendorRoot = join(repoRoot, 'third_party/reference-finder');
const coreDir = join(vendorRoot, 'src/core');
const objDir = join(repoRoot, 'target/reference-finder-obj');
const webOutDir = join(repoRoot, 'apps/web/src/generated/reference-finder');
const nodeOutDir = join(repoRoot, 'artifacts/reference-finder-node');

const args = new Set(process.argv.slice(2));
if (args.has('--help') || args.has('-h')) {
  console.log(
    'usage: node scripts/build-reference-finder.mjs [--node]\n\n' +
      '  --node   also link a worker+node variant to artifacts/reference-finder-node/\n\n' +
      'env:\n' +
      '  REFERENCE_FINDER_FORCE_SOURCE=1   never fall back to the upstream artifact'
  );
  process.exit(0);
}
for (const arg of args) {
  if (arg !== '--node') fail(`unknown argument ${arg} (see --help)`);
}
const wantNode = args.has('--node');
const forceSource = process.env.REFERENCE_FINDER_FORCE_SOURCE === '1';

const pin = JSON.parse(readFileSync(pinPath, 'utf8'));

// Flags copied from third_party/reference-finder/makefile. The makefile is the authoritative
// list and is never run directly (its RFVersion.h rule shells out to `pnpm gulp` and it
// writes inside the vendored tree). `make` expands the implicit rules as
//   COMPILE.cc = $(CXX) $(CXXFLAGS) $(CPPFLAGS) -c        (makefile line 56)
//   LINK.cc    = $(CXX) $(CXXFLAGS) $(CPPFLAGS) $(LDFLAGS) (makefile line 50)
// so CXXFLAGS and CPPFLAGS go to both the compile and the link step.
const CPPFLAGS = ['-I' + coreDir, '-std=c++17']; // makefile line 16
const CXXFLAGS = ['-O3', '-flto']; // makefile line 17
const LDFLAGS = [
  // makefile lines 18–28
  '-lidbfs.js',
  '-sINITIAL_MEMORY=50MB',
  '-sALLOW_MEMORY_GROWTH',
  '-sASYNCIFY=1',
  // Upstream says 120000 (makefile line 23). emcc >= 6 rejects anything below its Safari
  // floor of 15.0, so this is the one deliberate divergence from the makefile.
  '-sMIN_SAFARI_VERSION=150000',
  '-sASSERTIONS',
  '-sMAXIMUM_MEMORY=4GB',
  '-sEXPORT_ES6=1',
  '-sEXPORTED_RUNTIME_METHODS=wasmMemory',
];
const WEB_ENVIRONMENT = '-sENVIRONMENT=worker'; // makefile line 28
const NODE_ENVIRONMENT = '-sENVIRONMENT=worker,node'; // our test-only variant

const REF_D_TS = `// Generated by scripts/build-reference-finder.mjs — do not edit.
//
// Type surface of the Emscripten glue for the ReferenceFinder core. The C++ side talks to
// JavaScript only through the hooks below (third_party/reference-finder/src/core/utils.h):
// it pulls every input number with \`await Module.get()\`, polls \`Module.checkCancel()\`
// while a statistics run is in flight, and calls \`Module.clear()\` before it prints the
// "Ready" prompt for the next command. Everything it says comes back through \`print\`
// (stdout: progress lines, "Ready", and one JSON solution per line) and \`printErr\`.

export interface RefModule {
  /** stdout, one call per line. "Ready" delimits commands. */
  print(text: string): void;
  /** stderr, one call per line (validation errors, "Unknown command"). */
  printErr(text: string): void;
  /** Next number from the input queue; the core awaits this for every ReadNumber(). */
  get(): Promise<number> | number;
  /** Polled during statistics runs; resolve true to cancel. */
  checkCancel(): Promise<boolean> | boolean;
  /** Called before each "Ready": drop any queued input the last command did not consume. */
  clear(): void;
  /** Resolve the .wasm URL; the default is relative to the glue script. */
  locateFile?(path: string, scriptDirectory: string): string;
  /**
   * Supply the compiled module yourself (e.g. from a bundler URL or an in-memory copy).
   * Call \`receiveInstance\` when ready and return an empty object, per Emscripten.
   */
  instantiateWasm?(
    imports: WebAssembly.Imports,
    receiveInstance: (instance: WebAssembly.Instance, module?: WebAssembly.Module) => void
  ): WebAssembly.Exports | Record<string, never>;
  /** Exported by -sEXPORTED_RUNTIME_METHODS=wasmMemory; populated once the module is up. */
  wasmMemory: WebAssembly.Memory;
}

declare const createReferenceFinderModule: (moduleArg?: Partial<RefModule>) => Promise<RefModule>;
export default createReferenceFinderModule;
`;

main().catch((error) => fail(error instanceof Error ? error.message : String(error)));

async function main() {
  const targets = [
    { dir: webOutDir, environment: WEB_ENVIRONMENT, label: 'web' },
    ...(wantNode ? [{ dir: nodeOutDir, environment: NODE_ENVIRONMENT, label: 'node' }] : []),
  ];
  const stale = targets.filter((target) => !isUpToDate(target.dir));

  if (stale.length === 0) {
    console.log(`reference-finder: up to date (${targets.map((t) => t.label).join(', ')})`);
    writeIfChanged(join(webOutDir, 'ref.d.ts'), REF_D_TS);
    return;
  }

  const emxx = findEmxx();
  if (!emxx) {
    if (forceSource) {
      fail(
        'em++ is not on PATH and REFERENCE_FINDER_FORCE_SOURCE=1 forbids the upstream fallback.\n' +
          emsdkHint()
      );
    }
    if (wantNode) {
      fail(
        'em++ is not on PATH; the --node variant can only be built from source ' +
          '(the upstream artifact is worker-only).\n' +
          emsdkHint()
      );
    }
    if (outputsExist(webOutDir)) {
      console.warn(
        'reference-finder: WARNING em++ is not on PATH; keeping the existing (stale) ' +
          `${relative(repoRoot, webOutDir)} instead of rebuilding.\n` +
          emsdkHint()
      );
      writeIfChanged(join(webOutDir, 'ref.d.ts'), REF_D_TS);
      return;
    }
    await fetchUpstreamFallback();
    writeIfChanged(join(webOutDir, 'ref.d.ts'), REF_D_TS);
    return;
  }

  checkEmccVersion(emxx);

  const started = performance.now();
  const sources = listFiles(coreDir).filter((file) => file.endsWith('.cpp'));
  if (sources.length === 0) fail(`no .cpp sources found under ${relative(repoRoot, coreDir)}`);

  const objects = await compileAll(emxx, sources);
  for (const target of stale) {
    await link(emxx, objects, target);
  }
  writeIfChanged(join(webOutDir, 'ref.d.ts'), REF_D_TS);

  const seconds = ((performance.now() - started) / 1000).toFixed(1);
  console.log(
    `reference-finder: built ${stale.map((t) => relative(repoRoot, t.dir)).join(', ')} ` +
      `from ${sources.length} sources in ${seconds}s`
  );
}

// ---------------------------------------------------------------------------------------
// Up-to-date check

function outputsExist(dir) {
  return existsSync(join(dir, 'ref.js')) && existsSync(join(dir, 'ref.wasm'));
}

function isUpToDate(dir) {
  if (!outputsExist(dir)) return false;
  const outputMtime = Math.min(mtime(join(dir, 'ref.js')), mtime(join(dir, 'ref.wasm')));
  const inputs = [...listFiles(coreDir), scriptPath, pinPath];
  return inputs.every((file) => mtime(file) < outputMtime);
}

function mtime(file) {
  return statSync(file).mtimeMs;
}

function listFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(full));
    else if (entry.isFile()) out.push(full);
  }
  return out.sort();
}

// ---------------------------------------------------------------------------------------
// Toolchain

function findEmxx() {
  const probe = spawnSync('em++', ['--version'], { encoding: 'utf8' });
  return probe.error || probe.status !== 0 ? null : 'em++';
}

function checkEmccVersion(emxx) {
  const probe = spawnSync(emxx, ['--version'], { encoding: 'utf8' });
  const match = /(\d+\.\d+\.\d+)/.exec(probe.stdout ?? '');
  const installed = match ? match[1] : 'unknown';
  if (installed !== pin.emsdk) {
    console.warn(
      `reference-finder: WARNING em++ is ${installed}; the pinned toolchain is Emscripten ` +
        `${pin.emsdk} (${relative(repoRoot, pinPath)}). Building anyway.`
    );
  }
}

function emsdkHint() {
  return (
    `Install Emscripten ${pin.emsdk} (https://emscripten.org/docs/getting_started/downloads.html):\n` +
    `  git clone https://github.com/emscripten-core/emsdk.git && cd emsdk\n` +
    `  git checkout ${pin.emsdkRepoCommit}\n` +
    `  ./emsdk install ${pin.emsdk} && ./emsdk activate ${pin.emsdk} && source ./emsdk_env.sh\n` +
    `or \`brew install emscripten\` on macOS.`
  );
}

// ---------------------------------------------------------------------------------------
// Compile + link

async function compileAll(emxx, sources) {
  const jobs = sources.map((source) => {
    const object = join(objDir, relative(coreDir, source).replace(/\.cpp$/, '.o'));
    return { source, object };
  });
  // Objects are shared by the web and node links (the environment is a link flag), so a
  // second link right after the first reuses them. Header edits are not tracked per object;
  // any input newer than an object invalidates it.
  const newestInput = Math.max(...[...listFiles(coreDir), scriptPath, pinPath].map(mtime));
  const pending = jobs.filter((job) => !(existsSync(job.object) && mtime(job.object) > newestInput));
  const parallelism = Math.max(1, cpus().length);
  console.log(
    `reference-finder: compiling ${pending.length} of ${jobs.length} sources with em++ (-j${parallelism})`
  );

  let next = 0;
  const worker = async () => {
    while (next < pending.length) {
      const job = pending[next++];
      mkdirSync(dirname(job.object), { recursive: true });
      await run(emxx, [...CXXFLAGS, ...CPPFLAGS, '-c', job.source, '-o', job.object], {
        what: `compile ${relative(coreDir, job.source)}`,
      });
    }
  };
  await Promise.all(Array.from({ length: Math.min(parallelism, pending.length) }, worker));
  return jobs.map((job) => job.object);
}

async function link(emxx, objects, target) {
  mkdirSync(target.dir, { recursive: true });
  console.log(`reference-finder: linking ${relative(repoRoot, target.dir)}/ref.{js,wasm}`);
  await run(
    emxx,
    [...CXXFLAGS, ...CPPFLAGS, ...LDFLAGS, target.environment, '-o', join(target.dir, 'ref.js'), ...objects],
    { what: `link ${target.label}` }
  );
  if (!outputsExist(target.dir)) {
    fail(`link ${target.label} produced no ref.js/ref.wasm under ${relative(repoRoot, target.dir)}`);
  }
  if (target.label === 'node') {
    // ref.js is ES module syntax; without a nearby "type": "module" Node reparses it and warns.
    writeIfChanged(join(target.dir, 'package.json'), '{ "type": "module" }\n');
  }
}

function run(command, commandArgs, { what }) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, commandArgs, { stdio: ['ignore', 'pipe', 'pipe'] });
    let output = '';
    child.stdout.on('data', (chunk) => (output += chunk));
    child.stderr.on('data', (chunk) => (output += chunk));
    child.on('error', (error) => reject(new Error(`${what}: ${error.message}`)));
    child.on('close', (code) => {
      if (code === 0) {
        if (output.trim()) process.stderr.write(output);
        resolvePromise();
      } else {
        reject(new Error(`${what} failed (exit ${code}):\n${output}`));
      }
    });
  });
}

// ---------------------------------------------------------------------------------------
// Upstream fallback

async function fetchUpstreamFallback() {
  const base = `https://raw.githubusercontent.com/MuTsunTsai/reference-finder/${pin.pinnedUpstreamCommit}/src/lib/`;
  console.warn(
    'reference-finder: WARNING em++ is not on PATH; fetching upstream\'s committed artifact at ' +
      `${pin.pinnedUpstreamCommit.slice(0, 7)} as a development fallback.\n` +
      'This binary is never shipped: CI sets REFERENCE_FINDER_FORCE_SOURCE=1.\n' +
      emsdkHint()
  );
  mkdirSync(webOutDir, { recursive: true });
  for (const name of ['ref.js', 'ref.wasm']) {
    const expected = pin.fallbackSha256[name];
    if (!expected) fail(`${relative(repoRoot, pinPath)} has no fallbackSha256 entry for ${name}`);
    const response = await fetch(base + name);
    if (!response.ok) {
      fail(`download of ${base + name} failed: HTTP ${response.status} ${response.statusText}`);
    }
    const bytes = Buffer.from(await response.arrayBuffer());
    const actual = createHash('sha256').update(bytes).digest('hex');
    if (actual !== expected) {
      fail(
        `SHA-256 mismatch for upstream ${name}:\n  expected ${expected}\n  actual   ${actual}\n` +
          'Refusing to use the download. Either upstream rewrote history at the pinned commit ' +
          'or the transfer was tampered with; build from source instead.\n' +
          emsdkHint()
      );
    }
    const tmp = join(webOutDir, `${name}.tmp`);
    writeFileSync(tmp, bytes);
    renameSync(tmp, join(webOutDir, name));
    console.log(`reference-finder: fetched ${name} (${bytes.length} bytes, sha256 ok)`);
  }
}

// ---------------------------------------------------------------------------------------

function writeIfChanged(file, content) {
  mkdirSync(dirname(file), { recursive: true });
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

function fail(message) {
  console.error(`reference-finder: error: ${message}`);
  process.exit(1);
}
