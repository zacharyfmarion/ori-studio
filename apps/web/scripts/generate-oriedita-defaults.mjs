#!/usr/bin/env node
// Snapshot Oriedita's shipped default hotkey table into a TS module the browser bundle can use.
//
// An imported `.oriconfig` archive carries only the hotkeys the user *edited* — Oriedita's
// 232-action default table lives inside the jar and never reaches the app dir. Reconstructing
// a user's effective keymap (defaults ⊕ deltas) therefore needs those defaults at runtime, and
// `third_party/` is not shipped to the browser. Hence the snapshot.
//
// Only the actions that ship *with* a binding are emitted: an empty default carries no
// information, and the absent-vs-empty distinction is meaningless on this side of the import
// (see the merge-semantics table in implementation-plans/oriedita-settings-import.md).
//
// Run from apps/web: npm run generate:oriedita-defaults

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, '..', '..', '..');

const SOURCE_RELATIVE = 'third_party/oriedita/oriedita/src/main/resources/hotkey.properties';
const OUTPUT_RELATIVE = 'apps/web/src/lib/orieditaImport/orieditaDefaultHotkeys.generated.ts';

/**
 * Parse the vendored hotkey.properties into `{ action: keystroke }`, keeping only non-empty
 * values.
 *
 * This is deliberately *not* a general java.util.Properties reader: the vendored file uses one
 * plain `key=value` per line, and a half-implemented general parser would mis-read a construct
 * rather than refuse it. Anything outside that shape throws, so an upstream file that grows
 * continuations or `\uXXXX` escapes stops the generator instead of silently dropping bindings.
 *
 * @param {string} text
 * @returns {{ entries: Record<string, string>, keyCount: number }}
 */
export function deriveDefaultHotkeys(text) {
  /** @type {Record<string, string>} */
  const entries = {};
  const seen = new Set();

  text.split(/\r?\n/).forEach((line, index) => {
    const where = `${SOURCE_RELATIVE}:${index + 1}`;
    const trimmed = line.trim();
    if (trimmed === '' || trimmed.startsWith('#') || trimmed.startsWith('!')) return;

    if (trimmed.endsWith('\\')) {
      throw new Error(`${where}: line continuation is not supported; extend the generator.`);
    }
    if (trimmed.includes('\\u')) {
      throw new Error(`${where}: \\uXXXX escape is not supported; extend the generator.`);
    }

    const separator = trimmed.indexOf('=');
    if (separator === -1) {
      throw new Error(`${where}: expected a "key=value" line, got ${JSON.stringify(trimmed)}.`);
    }

    const action = trimmed.slice(0, separator).trim();
    const keystroke = trimmed.slice(separator + 1).trim();
    if (action === '') {
      throw new Error(`${where}: empty action name.`);
    }
    if (seen.has(action)) {
      throw new Error(`${where}: duplicate action ${action}.`);
    }

    seen.add(action);
    if (keystroke !== '') entries[action] = keystroke;
  });

  return { entries, keyCount: seen.size };
}

/**
 * @param {Record<string, string>} entries
 * @param {number} keyCount
 * @returns {string}
 */
function renderModule(entries, keyCount) {
  // Single quotes to match the repo's TS style.
  const quote = (/** @type {string} */ value) =>
    `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
  const bound = Object.entries(entries)
    .map(([action, keystroke]) => `  ${quote(action)}: ${quote(keystroke)},`)
    .join('\n');

  return `// @generated by \`npm run generate:oriedita-defaults\` (apps/web/scripts/generate-oriedita-defaults.mjs).
// Source of truth: ${SOURCE_RELATIVE}
// DO NOT EDIT BY HAND — re-run the script instead. orieditaDefaultHotkeys.test.ts re-reads the
// vendored file and fails if this snapshot has drifted from it.
//
// Oriedita's shipped defaults for the actions that ship *with* a binding. ${
    Object.keys(entries).length
  } of ${keyCount}
// actions are bound upstream; the rest ship unbound and are omitted, since an empty default
// says nothing. Values are Java \`KeyStroke\` strings, parsed by parseKeyStroke.ts.

export const ORIEDITA_DEFAULT_HOTKEYS: Readonly<Record<string, string>> = {
${bound}
};
`;
}

const sourcePath = join(REPO_ROOT, SOURCE_RELATIVE);
const outputPath = join(REPO_ROOT, OUTPUT_RELATIVE);

const { entries, keyCount } = deriveDefaultHotkeys(readFileSync(sourcePath, 'utf8'));
writeFileSync(outputPath, renderModule(entries, keyCount));

console.log(
  `Wrote ${OUTPUT_RELATIVE}: ${Object.keys(entries).length} bound of ${keyCount} actions.`
);
