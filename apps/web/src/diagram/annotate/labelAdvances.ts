/**
 * The widest a CJK font sets `codePoint` at among CJK words, Regular or
 * `bold` (17b), in thousandths of an em; null where none has it.
 */
export function cjkRunAdvance(codePoint: number, bold = false): number | null {
  return advanceIn(bold ? CJK_RUN_BOLD_ADVANCE_RUNS : CJK_RUN_ADVANCE_RUNS, codePoint);
}

/** A code point's advance in a table of runs; null where it has none, or a -1 between runs. */
function advanceIn(runs: readonly LabelAdvanceRun[], codePoint: number): number | null {
  for (const run of runs) {
    const advance = run.advances[codePoint - run.from];
    if (advance !== undefined) return advance >= 0 ? advance : null;
  }
  return null;
}
