/** Noto Sans Regular's advance for `codePoint`, in thousandths of an em; null where it has no glyph. */
export function labelAdvance(codePoint: number): number | null {
  for (const run of LABEL_ADVANCE_RUNS) {
    const advance = run.advances[codePoint - run.from];
    if (advance !== undefined) return advance >= 0 ? advance : null;
  }
  return null;
}
