import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { beforeEach, describe, expect, it, vi } from 'vitest';

import {
  createOristudioCpNativeClient,
  decodeCompactGeometryBytes,
  encodeCompactGeometryBytes,
} from './oristudioCpNativeClient';

const invoke = vi.hoisted(() => vi.fn());
vi.mock('@tauri-apps/api/core', () => ({ invoke }));

// The cross-language pin for the compact-geometry wire format.
//
// These bytes are not written here — they are read from a fixture the Rust
// encoder produces (`binary_codec_golden_fixture_is_current` in
// crates/oristudio-cp/src/geometry_transport.rs), so there is no copy of them
// to fall out of date. Change the format and that Rust test fails until the
// fixture is regenerated; the regenerated bytes then arrive here, and this test
// fails until the decoder below understands them.
//
// It used to be an inline array, and it went stale: the format moved OCG1 ->
// OCG2 and this file stayed on OCG1, so the suite passed while every payload
// from the native engine failed its magic check and the desktop editor opened
// nothing at all.
//
// Resolved from the vitest root (apps/web) rather than from this file: Vite
// rewrites `import.meta.url` during transform, so it is not a filesystem path.
const GOLDEN_FIXTURE = resolve(
  process.cwd(),
  '../../tests/fixtures/oristudio-cp/compact-geometry-golden.bin'
);

function readGoldenFixture(): Uint8Array {
  try {
    return new Uint8Array(readFileSync(GOLDEN_FIXTURE));
  } catch (error) {
    throw new Error(
      `compact-geometry golden fixture not found at ${GOLDEN_FIXTURE}. ` +
        'It is generated by the Rust encoder: ' +
        'UPDATE_FIXTURES=1 cargo test -p oristudio-cp --lib binary_codec_golden',
      { cause: error }
    );
  }
}

const GOLDEN_BYTES = readGoldenFixture();

function bufferOf(bytes: Uint8Array): ArrayBuffer {
  // A standalone ArrayBuffer copy (offset 0), matching what invoke returns.
  return bytes.slice().buffer;
}

describe('decodeCompactGeometryBytes', () => {
  // Fails first, and most legibly, when the encoder moves on.
  it('is a current-version buffer, not a stale one', () => {
    const magic = new DataView(bufferOf(GOLDEN_BYTES)).getUint32(0, true);
    expect(String.fromCharCode(...GOLDEN_BYTES.slice(0, 4))).toBe('3GCO'); // "OCG3", little-endian
    expect(magic).toBe(0x4f_43_47_33);
  });

  it('decodes the real Rust-encoded golden buffer', () => {
    const geometry = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
    expect(Array.from(geometry.segEndpoints)).toEqual([1, 2, 3, 4]);
    // Five per segment since OCG3: colour, active, selected, customized, hint.
    expect(Array.from(geometry.segAttr)).toEqual([5, 6, 7, 8, 0]);
    expect(Array.from(geometry.segCustomColor)).toEqual([9, 10, 11]);
    // Empty means "every segment is classic" — the common case, and what the
    // encoder writes when no segment carries a magnitude.
    expect(Array.from(geometry.segFoldMagnitude ?? [])).toEqual([]);
    expect(Array.from(geometry.auxEndpoints)).toEqual([]);
    expect(Array.from(geometry.pointCoords)).toEqual([12, 13]);
    expect(Array.from(geometry.circleData)).toEqual([]);
    // Tail round-trips through JSON (grid/operationFrame present by default).
    expect(geometry.tail).toBeTruthy();
    // Views are real typed arrays.
    expect(geometry.segEndpoints).toBeInstanceOf(Float64Array);
    expect(geometry.segAttr).toBeInstanceOf(Int32Array);
    expect(geometry.segCustomColor).toBeInstanceOf(Uint8Array);
  });

  it('throws on a bad magic', () => {
    const bytes = GOLDEN_BYTES.slice();
    bytes[0] ^= 0xff;
    expect(() => decodeCompactGeometryBytes(bufferOf(bytes))).toThrow();
  });

  // The exact shape of the bug this file failed to catch: a previous-version
  // buffer must be refused outright rather than misparsed.
  it('refuses a previous-version (OCG1) buffer', () => {
    const bytes = GOLDEN_BYTES.slice();
    bytes[0] = '1'.charCodeAt(0); // OCG3 -> OCG1
    expect(() => decodeCompactGeometryBytes(bufferOf(bytes))).toThrow(
      expect.objectContaining({ code: 'geometry_decode' })
    );
  });

  it('throws on a truncated buffer (length disagrees with header)', () => {
    const bytes = GOLDEN_BYTES.slice(0, GOLDEN_BYTES.length - 1);
    expect(() => decodeCompactGeometryBytes(bufferOf(bytes))).toThrow();
  });

  it('throws on a buffer too small for the header', () => {
    expect(() => decodeCompactGeometryBytes(new ArrayBuffer(4))).toThrow();
  });
});

// Undo on desktop sends geometry the other way, so the encoder is pinned to the
// same Rust bytes. Only the JSON tail may differ: `JSON.stringify` writes `1`
// where serde writes `1.0`, which the Rust decoder reads either way
// (`binary_codec_reads_a_tail_written_by_javascript`).
describe('encodeCompactGeometryBytes', () => {
  const TAIL_AT = 13 * 4;
  const tailLength = (bytes: Uint8Array) =>
    new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).getUint32(TAIL_AT - 4, true);

  it('writes the Rust header and arrays byte for byte', () => {
    const encoded = encodeCompactGeometryBytes(decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES)));
    expect(encoded.slice(0, TAIL_AT - 4)).toEqual(GOLDEN_BYTES.slice(0, TAIL_AT - 4));
    expect(encoded.slice(TAIL_AT + tailLength(encoded))).toEqual(
      GOLDEN_BYTES.slice(TAIL_AT + tailLength(GOLDEN_BYTES))
    );
  });

  it('round-trips through the decoder', () => {
    const geometry = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
    expect(decodeCompactGeometryBytes(bufferOf(encodeCompactGeometryBytes(geometry)))).toEqual(
      geometry
    );
  });

  it('writes an absent fold-magnitude array as an empty one', () => {
    const { segFoldMagnitude: _, ...rest } = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
    const decoded = decodeCompactGeometryBytes(bufferOf(encodeCompactGeometryBytes(rest)));
    expect(Array.from(decoded.segFoldMagnitude ?? [-1])).toEqual([]);
    expect(Array.from(decoded.pointCoords)).toEqual([12, 13]);
  });

  describe('as undo sends it', () => {
    beforeEach(() => {
      invoke.mockReset();
      invoke.mockResolvedValue(undefined);
    });

    it('is the raw body, with the handle and the task session as headers', async () => {
      const geometry = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
      await createOristudioCpNativeClient(3).restoreFromCompact(7, geometry);
      expect(invoke).toHaveBeenCalledWith('cp_restore_from_compact', expect.any(Uint8Array), {
        headers: { 'x-handle': '7', 'x-session-id': '3' },
      });
      const body = invoke.mock.calls[0]![1] as Uint8Array;
      expect(decodeCompactGeometryBytes(bufferOf(body))).toEqual(geometry);
      // A copy: the undo entry's arrays are still there to restore again.
      expect(Array.from(geometry.segEndpoints)).toEqual([1, 2, 3, 4]);
    });

    it('names no session for the main one', async () => {
      const geometry = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
      await createOristudioCpNativeClient().restoreFromCompact(7, geometry);
      expect(invoke).toHaveBeenCalledWith('cp_restore_from_compact', expect.any(Uint8Array), {
        headers: { 'x-handle': '7' },
      });
    });
  });

  it('reads only the view of an array that shares its buffer', () => {
    const geometry = decodeCompactGeometryBytes(bufferOf(GOLDEN_BYTES));
    const wide = new Float64Array([99, 12, 13, 99]);
    const decoded = decodeCompactGeometryBytes(
      bufferOf(encodeCompactGeometryBytes({ ...geometry, pointCoords: wide.subarray(1, 3) }))
    );
    expect(Array.from(decoded.pointCoords)).toEqual([12, 13]);
  });
});
